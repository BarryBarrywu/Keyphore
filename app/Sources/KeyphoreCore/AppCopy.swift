public enum AppCopy {
    public static func value(_ key: AppCopyKey) -> String {
        value(key, language: AppPreferencesStore().load().resolvedLanguage())
    }

    public static func value(_ key: AppCopyKey, language: AppLanguage) -> String {
        value(key, language: language, resources: .module)
    }

    static func value(
        _ key: AppCopyKey,
        language: AppLanguage,
        resources: Bundle
    ) -> String {
        let resourceNames = [language.rawValue, language.rawValue.lowercased(), "en"]
        for resource in resourceNames {
            guard let path = resources.path(forResource: resource, ofType: "lproj"),
                  let bundle = Bundle(path: path)
            else { continue }
            let value = bundle.localizedString(forKey: key.rawValue, value: key.rawValue, table: nil)
            if value != key.rawValue { return value }
        }
        return key.rawValue
    }
}

